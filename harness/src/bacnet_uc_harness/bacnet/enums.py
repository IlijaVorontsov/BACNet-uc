_PROPERTIES_CI = {k.lower(): v for k, v in PROPERTIES.items()}
_UNITS_CI = {k.lower(): v for k, v in UNITS.items()}


# --- helpers ------------------------------------------------------------------------------


def _norm(name: str) -> str:
    return name.strip().lower().replace("_", "-").replace(" ", "-")


def _lookup(value: str | int, table: dict[str, int], what: str, limit: int) -> int:
    if isinstance(value, bool):
        raise ValueError(f"invalid BACnet {what}: {value!r}")
    if isinstance(value, int):
        number = value
    elif isinstance(value, str):
        text = value.strip()
        if text.isdigit():
            number = int(text)
        else:
            try:
                return table[_norm(text)]
            except KeyError:
                raise ValueError(f"unknown BACnet {what}: {value!r}") from None
    else:
        raise ValueError(f"invalid BACnet {what}: {value!r}")
    if not 0 <= number <= limit:
        raise ValueError(f"BACnet {what} out of range: {number}")
    return number


def object_type_number(value: str | int) -> int:
    """Object type number of a name (``"analog-input"``, ``"analog_input"``,
    ``"AI"``), a decimal string or an int. Raises :class:`ValueError`."""
    if isinstance(value, str):
        abbr = OBJECT_TYPE_ABBREVIATIONS.get(value.strip().lower())
        if abbr is not None:
            return OBJECT_TYPES[abbr]
    return _lookup(value, _OBJECT_TYPES_CI, "object type", MAX_OBJECT_TYPE)


def property_number(value: str | int) -> int:
    """Property identifier of a name (``"present-value"``, ``"present_value"``),
    a decimal string or an int. Raises :class:`ValueError`."""
    return _lookup(value, _PROPERTIES_CI, "property", MAX_PROPERTY_ID)


def unit_number(value: str | int) -> int:
    """Engineering unit number of a name (``"degrees-celsius"``), a decimal
    string or an int. Raises :class:`ValueError`."""
    return _lookup(value, _UNITS_CI, "engineering unit", 0xFFFF)


