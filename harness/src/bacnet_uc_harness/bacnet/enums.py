def parse_object_ref(ref: str | tuple[str | int, int]) -> tuple[int, int]:
    """Parse an object reference into ``(type, instance)``.

    Accepts ``"analog-input:1"``, ``"analog-input,1"``, ``"analog-input 1"``,
    ``"AI:1"``, ``"0:1"`` or an existing ``(type, instance)`` pair.
    Raises :class:`ValueError`.
    """
    if isinstance(ref, tuple | list):
        if len(ref) != 2:
            raise ValueError(f"invalid object reference: {ref!r}")
        obj_type, instance = ref
        inst = int(instance)
    else:
        text = str(ref).strip()
        for sep in (":", ",", " ", "/"):
            if sep in text:
                obj_type, _, inst_text = text.rpartition(sep)
                break
        else:
            raise ValueError(f"invalid object reference (expected '<type>:<instance>'): {ref!r}")
        try:
            inst = int(inst_text.strip())
        except ValueError:
            raise ValueError(f"invalid object instance in {ref!r}") from None
    if not 0 <= inst <= MAX_INSTANCE:
        raise ValueError(f"object instance out of range in {ref!r}")
    return object_type_number(obj_type), inst


def format_object_ref(obj_type: str | int, instance: int) -> str:
    """``"analog-input:1"`` for ``(0, 1)``."""
    return f"{object_type_name(object_type_number(obj_type))}:{int(instance)}"
