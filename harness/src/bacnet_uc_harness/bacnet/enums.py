"""BACnet enumerations: object types, properties, engineering units, errors.

The name tables use the text names of the BACnet stack used by the firmware
(``bactext.c`` of bacnet-stack 54544d02e427), so names returned by the
node (``uc_node objects``, ``uc_io catalog``) and names accepted by it match
the ones here. ``PROPERTIES`` includes the stack's two mixed-case names
(``number-of-APDU-retries``, ``COV-period``); lookups are case-insensitive
and accept ``_`` or spaces in place of ``-``.

The tables from ``OBJECT_TYPES`` to ``UNCONFIRMED_SERVICES`` were generated
by dumping the ``INDTEXT_DATA`` tables of bactext.c; the service names were
converted to lower-case hyphenated form (``ReadProperty`` ->
``read-property``) and the ``error-code-`` prefix of one error code name was
dropped. Reject/abort reasons, constants and helpers are hand-written.
"""

