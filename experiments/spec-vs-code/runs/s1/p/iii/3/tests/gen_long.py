#!/usr/bin/env python3
"""Independent reference for long-value vectors (formatting mirrors driver.c)."""
def fnv(b):
    h = 1469598103934665603
    for x in b:
        h ^= x; h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h
def pb(b):
    if not b: return "-"
    if len(b) <= 64: return b.hex()
    return b[:16].hex() + "..%016x/%d" % (fnv(b), len(b))
def hdr(tag, n):
    b0 = tag << 4
    if n <= 4: return bytes([b0 | n])
    if n <= 253: return bytes([b0 | 5, n])
    if n <= 65535: return bytes([b0 | 5, 254]) + n.to_bytes(2, "big")
    return bytes([b0 | 5, 255]) + n.to_bytes(4, "big")
out = ["# generated by tests/gen_long.py"]
def blk(name, inp, exp):
    out.append("### " + name); out.extend(inp); out.append("---"); out.extend(exp)
for n in (5, 253, 254, 255, 65535, 65536, 70000):
    data = bytes([0xab]) * n
    enc = hdr(6, n) + data
    blk(f"long-octets-{n}", [f"enc_octets rep:ab:{n} @{len(enc)+3}"], ["OK " + pb(enc)])
    blk(f"long-octets-{n}-cap", [f"enc_octets rep:ab:{n} @{len(enc)}", f"enc_octets rep:ab:{n} @{len(enc)-1}"], ["OK " + pb(enc), "ERR"])
    blk(f"long-octets-{n}-dec", [f"dec_app {enc[:len(enc)-n].hex()}+rep:ab:{n}+00", f"dec_app {enc[:len(enc)-n].hex()}+rep:ab:{n-1}"],
        [f"OK n={len(enc)} oct " + pb(data), "ERR"])
for n in (4, 252, 253, 65534, 65535):
    data = bytes([0x41]) * n
    enc = hdr(7, n + 1) + b"\x00" + data
    blk(f"long-str-{n}", [f"enc_str rep:41:{n} @{len(enc)}", f"enc_str rep:41:{n} @{len(enc)-1}"], ["OK " + pb(enc), "ERR"])
    blk(f"long-str-{n}-dec", [f"dec_app {enc.hex() if len(enc) < 300 else enc[:len(enc)-n].hex() + '+rep:41:' + str(n)}"],
        [f"OK n={len(enc)} str cs=0 " + pb(data)])
for n in (7, 8, 9, 31, 32, 33, 300, 2016, 2017, 70000):
    nb = (n + 7) // 8
    unused = (8 - n % 8) % 8
    packed = bytearray(nb)
    for i in range(n):
        if i % 3 != 1: packed[i // 8] |= 0x80 >> (i % 8)
    enc = hdr(8, nb + 1) + bytes([unused]) + bytes(packed)
    digits = "".join("0" if i % 3 == 1 else "1" for i in range(n))
    blk(f"long-bits-{n}", [f"enc_bits {digits} @{len(enc)}", f"enc_bits {digits} @{len(enc)-1}", f"enc_bits {digits[:-1]}2 @{len(enc)}"],
        ["OK " + pb(enc), "ERR", "ERR"])
open(__file__.replace("gen_long.py", "long.vec"), "w").write("\n".join(out) + "\n")
